miss = [c for c in range(32, 127) if chr(c) not in G]
if miss:
    sys.exit('missing glyphs: %r' % [chr(c) for c in miss])

enc = ''
for c in range(32, 127):
    for row in G[chr(c)]:
        v = 0
        for i, ch in enumerate(row):
            if ch == H:
                v |= 1 << i
        assert v <= 31
        enc += chr(64 + v)

assert len(enc) == 95 * 7
assert all(ord(ch) < 127 for ch in enc)
enc = enc.replace('\\', '\\\\').replace('"', '\\"')

lines = []
lines.append('fn gui_font_rows() -> ptr<u8> {')
lines.append('    return "%s";' % enc)
lines.append('}')
lines.append('')
lines.append('fn gui_font_row(c: i64, r: i64) -> u8 {')
lines.append('    if (c < 32 || c > 126 || r < 0 || r > 6) {')
lines.append('        return 0;')
lines.append('    }')
lines.append('    let t: ptr<u8> = gui_font_rows();')
lines.append('    var v: u8 = 0;')
lines.append('    let at: i64 = (c - 32) * 7 + r;')
lines.append('    unsafe {')
lines.append('        v = t[at];')
lines.append('    }')
lines.append('    return ((v - 64) as u8) & 31;')
lines.append('}')
lines.append('')

out = sys.argv[1] if len(sys.argv) > 1 else 'text/font.rsx'
with open(out, 'w', newline='\n') as f:
    f.write('\n'.join(lines))
print('wrote %s: 95 glyphs, %d bytes of table' % (out, len(enc)))
