def point_hex(curve, k):
    priv = ec.derive_private_key(k, curve)
    pub = priv.public_key().public_numbers()
    size = (curve.key_size + 7) // 8
    return format(pub.x, '0%dx' % (size * 2)), format(pub.y, '0%dx' % (size * 2))


def spki_hex(curve, k):
    priv = ec.derive_private_key(k, curve)
    return priv.public_key().public_bytes(Encoding.DER, PublicFormat.SubjectPublicKeyInfo).hex()


P256 = ec.SECP256R1()
P384 = ec.SECP384R1()

curves = [
    ('p256', P256, 0, 32),
    ('p384', P384, 1, 48),
]

rows = []
for name, curve, cid, width in curves:
    values = {'name': name, 'cid': cid, 'width': width}
    values['gx'], values['gy'] = point_hex(curve, 1)
    values['two_x'], values['two_y'] = point_hex(curve, 2)
    values['three_x'], values['three_y'] = point_hex(curve, 3)
    k = 0x11223344556677889900aabbccddeeff1234
    values['k_hex'] = format(k, 'x')
    values['kx'], values['ky'] = point_hex(curve, k)
    values['spki1'] = spki_hex(curve, 1)
    rows.append(values)

ecdsa_cases = []
for name, curve, cid, width in curves:
    digest = bytes(range(width))
    for k in (1, 0xdeadbeefcafe):
        priv = ec.derive_private_key(k, curve)
        algorithm = ec.ECDSA(utils.Prehashed(hashes.SHA256() if width == 32 else hashes.SHA384()))
        sig = priv.sign(digest, algorithm)
        ecdsa_cases.append({
            'name': name,
            'spki': spki_hex(curve, k),
            'digest': digest.hex(),
            'digest_len': len(digest),
            'sig': sig.hex(),
        })

