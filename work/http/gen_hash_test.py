import hashlib, pathlib

work = pathlib.Path(r'C:\Users\1234.DESKTOP-KICPMJN\Downloads\ms[r\rsharp\work\http')

cases = []
for n in (0, 1, 3, 55, 56, 57, 63, 64, 65, 127, 128, 129, 1000, 4096):
    data = b'a' * n
    cases.append((n, hashlib.sha1(data).hexdigest(), hashlib.sha384(data).hexdigest(),
                  hashlib.sha512(data).hexdigest()))

L = []
a = L.append
a('// work/http/t_hash.rsx — SHA-1, SHA-384, SHA-512 against hashlib.')
a('// Generated by gen_hash_test.py.')
a('include "../../modules/http/sha1.rsx";')
a('include "../../modules/http/sha512.rsx";')
a('')
a('fn check(name: ptr<u8>, got: ptr<u8>, want: ptr<u8>) -> i32 {')
a('    if (rt_eq(got, want) == 1) {')
a('        return 1;')
a('    }')
a('    printf("%s FAIL\\n   got  %s\\n   want %s\\n", name, got, want);')
a('    return 0;')
a('}')
a('')
a('fn main() -> i32 {')
a('    var ok: i32 = 0;')
a('    var total: i32 = 0;')
a('    var buf: [u8; 8192] = [0];')
a('    var bp: ptr<u8> = null;')
a('    unsafe { bp = &mut buf[0] as ptr<u8>; }')
a('    var h: [u8; 64] = [0];')
a('    var hp: ptr<u8> = null;')
a('    unsafe { hp = &mut h[0] as ptr<u8>; }')
a('    var hex: [u8; 160] = [0];')
a('    var hx: ptr<u8> = null;')
a('    unsafe { hx = &mut hex[0] as ptr<u8>; }')
a('    var i: i64 = 0;')
a('')
for n, s1, s384, s512 in cases:
    a('    i = 0;')
    a('    while (i < %d) {' % n)
    a('        buf[i] = 97;')
    a('        i += 1;')
    a('    }')
    a('    sha1(bp, %d, hp);' % n)
    a('    rt_hex_str(hx, hp, 20);')
    a('    ok += check("sha1_%d", hx, "%s");' % (n, s1))
    a('    total += 1;')
    a('    sha384(bp, %d, hp);' % n)
    a('    rt_hex_str(hx, hp, 48);')
    a('    ok += check("sha384_%d", hx, "%s");' % (n, s384))
    a('    total += 1;')
    a('    sha512(bp, %d, hp);' % n)
    a('    rt_hex_str(hx, hp, 64);')
    a('    ok += check("sha512_%d", hx, "%s");' % (n, s512))
    a('    total += 1;')
    a('')

a('    // Streaming update in awkward chunks must match the one-shot result.')
a('    i = 0;')
a('    while (i < 300) {')
a('        buf[i] = 97;')
a('        i += 1;')
a('    }')
a('    var c1: Sha1 = zero(Sha1);')
a('    sha1_init(&mut c1);')
a('    sha1_update(&mut c1, bp, 1);')
a('    sha1_update(&mut c1, rt_add(bp, 1), 62);')
a('    sha1_update(&mut c1, rt_add(bp, 63), 237);')
a('    sha1_final(&mut c1, hp);')
a('    rt_hex_str(hx, hp, 20);')
a('    ok += check("sha1_stream", hx, "%s");' % hashlib.sha1(b'a' * 300).hexdigest())
a('    total += 1;')
a('')
a('    var c2: Sha512 = zero(Sha512);')
a('    sha512_init(&mut c2);')
a('    sha512_update(&mut c2, bp, 127);')
a('    sha512_update(&mut c2, rt_add(bp, 127), 1);')
a('    sha512_update(&mut c2, rt_add(bp, 128), 172);')
a('    sha512_final(&mut c2, hp);')
a('    rt_hex_str(hx, hp, 64);')
a('    ok += check("sha512_stream", hx, "%s");' % hashlib.sha512(b'a' * 300).hexdigest())
a('    total += 1;')
a('')
a('    printf("hash_passed=%d of %d\\n", ok, total);')
a('    if (ok == total) {')
a('        return 0;')
a('    }')
a('    return 1;')
a('}')
a('')

(work / 't_hash.rsx').write_text('\n'.join(L), encoding='utf-8', newline='\r\n')
print('wrote t_hash.rsx')
