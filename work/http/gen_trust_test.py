"""Emit work/http/t_trust.rsx: path validation against the live Windows store.

One case per recorded chain, RSA and ECDSA, plus the negative cases that prove
the anchor walk is real: the leaf alone cannot terminate, a tampered
intermediate breaks the link, and the host and validity checks still bite.
"""
import json
import pathlib

work = pathlib.Path(r'C:\Users\1234.DESKTOP-KICPMJN\Downloads\ms[r\rsharp\work\http')
live = json.loads((work / 'certs' / 'live.json').read_text(encoding='utf-8'))
chains = live['chains']

L = []
a = L.append
a('// work/http/t_trust.rsx — real chains, real root store.')
a('// Generated by gen_trust_test.py. Every chain came off a live TLS handshake and')
a('// every anchor is whatever the Windows store trusts; nothing is pinned in the')
a('// module itself.')
a('include "../../modules/http/roots_win.rsx";')
a('include "../../modules/http/trust.rsx";')
a('')
a('fn check(name: ptr<u8>, got: i64, want: i64) -> i32 {')
a('    if (got == want) {')
a('        printf("%s ok\\n", name);')
a('        return 1;')
a('    }')
a('    printf("%s FAIL got=%lld want=%lld\\n", name, got, want);')
a('    return 0;')
a('}')
a('')
a('fn main() -> i32 {')
a('    var ok: i32 = 0;')
a('    var total: i32 = 0;')
a('')
a('    var stats: TrustStats = zero(TrustStats);')
a('    ok += check("store_open", trust_store_stats(&mut stats) as i64, 0);')
a('    total += 1;')
a('    printf("store count=%lld parsed=%lld\\n", stats.count, stats.parsed);')
a('    ok += check("store_all_parse", stats.parsed, stats.count);')
a('    total += 1;')
a('    ok += check("store_has_roots", stats.count, 294);')
a('    total += 1;')
a('')
a('    let now: i64 = rt_time();')
a('    printf("now=%lld\\n", now);')
a('')

for ci, chain in enumerate(chains):
    host = chain['host']
    leaflen = len(bytes.fromhex(chain['leaf']))
    interlen = len(bytes.fromhex(chain['inter']))
    a(f'    // ==== {host} ({chain["leaf_kind"]} leaf, {chain["inter_kind"]} intermediate) ====')
    a(f'    var lb_{ci}: [u8; 4096] = [0];')
    a(f'    var lp_{ci}: ptr<u8> = null;')
    a(f'    unsafe {{ lp_{ci} = &mut lb_{ci}[0] as ptr<u8>; }}')
    a(f'    let ll_{ci}: i64 = rt_parse_hex("{chain["leaf"]}", lp_{ci}, 4096);')
    a(f'    var ib_{ci}: [u8; 4096] = [0];')
    a(f'    var ip_{ci}: ptr<u8> = null;')
    a(f'    unsafe {{ ip_{ci} = &mut ib_{ci}[0] as ptr<u8>; }}')
    a(f'    let il_{ci}: i64 = rt_parse_hex("{chain["inter"]}", ip_{ci}, 4096);')
    a(f'    ok += check("leaf_len_{ci}", ll_{ci}, {leaflen});')
    a('    total += 1;')
    a(f'    ok += check("inter_len_{ci}", il_{ci}, {interlen});')
    a('    total += 1;')
    a('')
    a(f'    var cb_{ci}: [u8; 8192] = [0];')
    a(f'    var cp_{ci}: ptr<u8> = null;')
    a(f'    unsafe {{ cp_{ci} = &mut cb_{ci}[0] as ptr<u8>; }}')
    a(f'    rt_copy(cp_{ci}, lp_{ci}, ll_{ci});')
    a(f'    rt_copy(rt_add(cp_{ci}, ll_{ci}), ip_{ci}, il_{ci});')
    a(f'    var ch_{ci}: X509Chain = zero(X509Chain);')
    a(f'    x509_chain_init(&mut ch_{ci}, cp_{ci});')
    a(f'    x509_chain_add(&mut ch_{ci}, 0, ll_{ci});')
    a(f'    x509_chain_add(&mut ch_{ci}, ll_{ci}, il_{ci});')
    a('')
    a(f'    ok += check("verify_{ci}", trust_verify(&mut ch_{ci}, "{host}", rt_len("{host}"), now) as i64, 1);')
    a('    total += 1;')
    a(f'    ok += check("wrong_host_{ci}", trust_verify(&mut ch_{ci}, "www.example.org", rt_len("www.example.org"), now) as i64, 0);')
    a('    total += 1;')
    a(f'    ok += check("leaf_expired_{ci}", trust_verify(&mut ch_{ci}, "{host}", rt_len("{host}"), {chain["leaf_na"]} + 1) as i64, 0);')
    a('    total += 1;')
    a(f'    ok += check("inter_expired_{ci}", trust_verify(&mut ch_{ci}, "{host}", rt_len("{host}"), {chain["inter_na"]} + 1) as i64, 0);')
    a('    total += 1;')
    a(f'    ok += check("before_nb_{ci}", trust_verify(&mut ch_{ci}, "{host}", rt_len("{host}"), {chain["leaf_nb"]} - 1) as i64, 0);')
    a('    total += 1;')
    a('')
    a(f'    // Leaf alone: its issuer is an intermediate the store does not hold, so')
    a(f'    // the path cannot terminate. This is what proves the anchor walk works.')
    a(f'    var lone_{ci}: X509Chain = zero(X509Chain);')
    a(f'    x509_chain_init(&mut lone_{ci}, lp_{ci});')
    a(f'    x509_chain_add(&mut lone_{ci}, 0, ll_{ci});')
    a(f'    ok += check("no_anchor_{ci}", trust_verify(&mut lone_{ci}, "{host}", rt_len("{host}"), now) as i64, 0);')
    a('    total += 1;')
    a('')
    a(f'    // Corrupt the tail of the intermediate: the leaf signature no longer')
    a(f'    // verifies against the key it carries.')
    a(f'    var bad_{ci}: [u8; 8192] = [0];')
    a(f'    var bp_{ci}: ptr<u8> = null;')
    a(f'    unsafe {{ bp_{ci} = &mut bad_{ci}[0] as ptr<u8>; }}')
    a(f'    rt_copy(bp_{ci}, cp_{ci}, ll_{ci} + il_{ci});')
    a(f'    rt_setbyte(rt_add(bp_{ci}, ll_{ci} + il_{ci} - 8), 0, 0);')
    a(f'    var badch_{ci}: X509Chain = zero(X509Chain);')
    a(f'    x509_chain_init(&mut badch_{ci}, bp_{ci});')
    a(f'    x509_chain_add(&mut badch_{ci}, 0, ll_{ci});')
    a(f'    x509_chain_add(&mut badch_{ci}, ll_{ci}, il_{ci});')
    a(f'    ok += check("tampered_inter_{ci}", trust_verify(&mut badch_{ci}, "{host}", rt_len("{host}"), now) as i64, 0);')
    a('    total += 1;')
    a('')

a('    printf("trust_passed=%d of %d\\n", ok, total);')
a('    if (ok == total) {')
a('        return 0;')
a('    }')
a('    return 1;')
a('}')
a('')

(work / 't_trust.rsx').write_text('\n'.join(L), encoding='utf-8', newline='\r\n')
print('wrote t_trust.rsx')
